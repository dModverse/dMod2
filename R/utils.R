#' Alternative version of expand.grid
#' @param seq1 Vector, numeric or character
#' @param seq2 Vector, numeric or character
#' @return Matrix of combinations of elements of `seq1` and `seq2`
#' @noRd
expand.grid.alt <- function(seq1, seq2) {
  cbind(Var1=rep.int(seq1, length(seq2)), Var2=rep(seq2, each=length(seq1)))
}









#' Select Attributes
#'
#' Keeps or removes attributes of an object.
#'
#' @param x An object.
#' @param which Character vector of attribute names. `NULL` (default) stands for
#'   `"class"`, `"dim"`, `"dimnames"`, `"names"`, `"col.names"` and
#'   `"row.names"`.
#' @param keep Logical. `TRUE` (default) keeps the attributes in `which` and
#'   removes all others; `FALSE` removes those in `which`.
#'
#' @return `x` with the selected attributes.
#' @examples
#' x <- structure(1:3, names = c("a", "b", "c"), note = "temporary")
#' attrs(x)
#' attrs(x, "note", keep = FALSE)
#'   
#'   
#' @export
attrs <- function(x, which = NULL, keep = TRUE) {

  if (is.null(which)) {
    which <- c("class", "dim", "dimnames", "names", "col.names", "row.names")
  }
  
  listed <- names(attributes(x)) %in% which
  attributes(x) <- attributes(x)[if (keep) listed else !listed]
  x
}





# The derivative directions a constructor builds, in the order of `choices`.
# "none" stands alone; a second-order direction adds "forward", which it runs on.
.matchDerivMode <- function(x, choices = .derivModes) {
  if ("symbolic" %in% x)
    stop('derivMode = "symbolic" is gone: every derivative is generated by ',
         'AD at code-generation time. Use "forward".', call. = FALSE)
  choices <- c("none", choices)
  if (is.logical(x))
    stop("derivMode is logical: `deriv` and `deriv2` are not build arguments; derivMode selects ",
         "the derivatives to build, \"none\" for none, \"forward-forward\" for second order.",
         call. = FALSE)
  if (!is.character(x) || !length(x) || anyNA(x))
    stop("'derivMode' must name one or more of ",
         paste0('"', choices, '"', collapse = ", "), call. = FALSE)
  x <- unique(match.arg(x, choices, several.ok = TRUE))
  if ("none" %in% x && length(x) > 1L)
    stop('derivMode = "none" builds no derivatives and combines with no other ',
         "direction.", call. = FALSE)
  if (any(c("forward-forward", "forward-reverse") %in% x)) x <- c(x, "forward")
  choices[choices %in% x]
}

.derivModes <- c("forward", "reverse", "forward-forward", "forward-reverse")

# `deriv` and `deriv2` passed to a constructor that has `...`: an error that names derivMode.
.rejectBuildDeriv <- function(who, dots) {
  old <- intersect(c("deriv", "deriv2"), names(dots))
  if (!length(old)) return(invisible(NULL))
  stop(who, "(): ", paste0("`", old, "`", collapse = " and "),
       if (length(old) > 1L) " are not arguments; " else " is not an argument; ",
       "derivMode selects the derivatives to build, \"none\" for none, ",
       "\"forward-forward\" for second order.", call. = FALSE)
}

# The directions of cppFUN(), which builds forward over forward as `deriv2`.
.cppFUNMode <- function(derivMode) {
  m <- .setdiff(derivMode, c("none", "forward-forward"))
  if (length(m)) m else "forward"
}

# The error of a call that asks for a derivative direction the object was built without.
.notBuilt <- function(who, mode)
  stop(who, " was built without derivMode = \"", mode, "\"; this call needs it.",
       call. = FALSE)


# x with empty or missing names replaced by the prefix and the position
.fillNames <- function(x, prefix) {
  nms <- names(x)
  if (is.null(nms)) nms <- rep("", length(x))
  empty <- is.na(nms) | !nzchar(nms)
  nms[empty] <- paste0(prefix, which(empty))
  names(x) <- nms
  x
}

# set.seed() for the calling function; the random state of the session returns when that function does
.localSeed <- function(seed, frame = parent.frame()) {
  if (is.null(seed)) return(invisible(NULL))
  old <- get0(".Random.seed", envir = globalenv(), inherits = FALSE)
  restore <- function() {
    if (is.null(old)) rm(".Random.seed", envir = globalenv())
    else assign(".Random.seed", old, envir = globalenv())
  }
  do.call(on.exit, list(as.call(list(restore)), add = TRUE), envir = frame)
  set.seed(seed)
}
